#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description="Compare strict-v2 metrics produced from frozen runs.")
    parser.add_argument("metrics", nargs="+", type=Path)
    args = parser.parse_args()
    if len(args.metrics) < 2:
        parser.error("at least two metrics files are required")
    results = [json.loads(path.read_text(encoding="utf-8")) for path in args.metrics]
    first = results[0]
    warnings = ["Configurations may vary in multiple fields; original inference did not bind report hashes."]
    first_provenance = first["provenance"]
    for value in results[1:]:
        if (value["evaluation_protocol"] != first["evaluation_protocol"] or
            value["coverage"] != first["coverage"] or
            value["provenance"]["ground_truth_sha256"] != first["provenance"]["ground_truth_sha256"]):
            raise ValueError("Metrics use different ground truth, coverage, or evaluation protocol")
        provenance = value["provenance"]
        for field in ("evaluator_script_sha256", "evaluator_logic_sha256", "matching_logic_sha256"):
            if not first_provenance.get(field) or first_provenance[field] != provenance.get(field):
                raise ValueError(f"Metrics use different or missing {field}")
        if (first_provenance.get("run_config") or {}).get("model_id") != (provenance.get("run_config") or {}).get("model_id"):
            raise ValueError("Runs use different model IDs")
        for field in ("model_revision", "ontology_sha256", "class_map_sha256"):
            left = (first_provenance.get("run_result") or {}).get(field)
            right = (provenance.get("run_result") or {}).get(field)
            if left and right and left != right:
                raise ValueError(f"Runs use different {field}")
            if not left or not right:
                warnings.append(f"Missing {field}; compatibility is not verified")
        left_commit = (first_provenance.get("run_git") or {}).get("commit")
        right_commit = (provenance.get("run_git") or {}).get("commit")
        if left_commit and right_commit and left_commit != right_commit:
            warnings.append("Runs were generated by different commits")
        if not left_commit or not right_commit:
            warnings.append("Run commit missing; identical inference code is not verified")
    if any((item["provenance"].get("run_git") or {}).get("tracked_files_dirty") is not False for item in results):
        warnings.append("Tracked inference worktree was dirty or unknown")
    summary = []
    for path, value in zip(args.metrics, results, strict=True):
        provenance = value["provenance"]
        model_result = provenance.get("run_result") or {}
        summary.append({"metrics": str(path), "config": provenance.get("run_config"),
                        "git": provenance.get("run_git"), "model_revision": model_result.get("model_revision"),
                        "detector": value["detector"], "final_pipeline": value["final_pipeline"],
                        "sensitivity_no_ignore": value["sensitivity_no_ignore"]})
    print(json.dumps({"coverage": first["coverage"], "evaluation_protocol": first["evaluation_protocol"],
                      "warnings": sorted(set(warnings)),
                      "runs": summary}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
